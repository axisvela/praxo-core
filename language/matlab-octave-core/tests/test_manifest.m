function test_manifest()
root = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
vectors = praxo.parse_json(fileread(fullfile(root, 'spec', 'vectors', 'plugin.json')));
vectors = field(vectors, 'vectors').value;
for i = 1:numel(vectors)
    input = field(vectors{i}, 'input');
    expect = field(vectors{i}, 'expect');
    if any(strcmp(input.value(:, 1), 'raw'))
        raw = field(input, 'raw').value;
    else
        raw = praxo.encode_json(field(input, 'manifest'));
    end
    [valid, manifest] = praxo.validate_manifest(raw);
    assert(valid == field(expect, 'valid').value);
    if valid
        assert(isequal(manifest, praxo.parse_json(raw)));
    else
        assert(isempty(manifest));
    end
end
base = '{"schemaVersion":1,"id":"com.example.echo","version":"1.0.0","kind":"tool.provider.v1","entrypoint":{"type":"process","command":"echo"},"protocol":"jsonrpc-2","capabilities":[],"permissions":{},"limits":{},"health":{},"isolation":"process"}';
[valid, manifest] = praxo.validate_manifest(base);
assert(valid && strcmp(manifest.kind, 'object'));
bad = { ...
    '', '{}', 'null', [base '{}'], [base(1:end-1) ',"id":"com.example.echo"}'], ...
    strrep(base, '"schemaVersion":1', '"schemaVersion":true'), ...
    strrep(base, '"id":"com.example.echo"', '"id":"Com.example"'), ...
    strrep(base, '"version":"1.0.0"', '"version":"01.0.0"'), ...
    strrep(base, 'tool.provider.v1', 'other.provider.v1'), ...
    strrep(base, '"isolation":"process"', '"isolation":"wasm"'), ...
    strrep(base, '"command":"echo"', '"command":"echo","unknown":1'), ...
    strrep(base, '"command":"echo"', '"command":"echo","command":"x"'), ...
    strrep(base, '"command":"echo"', '"command":"echo","args":[1]'), ...
    strrep(base, '"capabilities":[]', '"capabilities":[""]'), ...
    strrep(base, '"capabilities":[]', '"capabilities":["a","a"]'), ...
    strrep(base, '"permissions":{}', '"permissions":{"filesystem":[{"path":"a/../b","mode":"read"}]}'), ...
    strrep(base, '"permissions":{}', '"permissions":{"filesystem":[{"path":"x","mode":"execute"}]}'), ...
    strrep(base, '"permissions":{}', '"permissions":{"network":[{"host":"x","port":65536}]}'), ...
    strrep(base, '"permissions":{}', '"permissions":{"network":[{"host":"x","port":1,"port":2}]}'), ...
    strrep(base, '"permissions":{}', '"permissions":{"env":["1BAD"]}'), ...
    strrep(base, '"limits":{}', '"limits":{"memoryMB":-1}'), ...
    strrep(base, '"limits":{}', '"limits":{"cpuMillis":1.5}'), ...
    strrep(base, '"limits":{}', '"limits":{"extra":0}'), ...
    strrep(base, '"health":{}', '"health":{"intervalMs":1}'), ...
    strrep(base, '"health":{}', '"health":{"method":null}'), ...
    [base(1:end-1) ',"signature":{"algorithm":"x"}}'], ...
    [base(1:end-1) ',"sbom":"../x"}'], ...
    [base(1:end-1) ',"sbom":"C:\\x"}'], ...
    strrep(base, '"permissions":{}', '"permissions":null'), ...
    strrep(base, '"capabilities":[],', '')};
for i = 1:numel(bad)
    [valid, manifest] = praxo.validate_manifest(bad{i});
    assert(~valid && isempty(manifest), sprintf('negative case %d', i));
end
good = strrep(base, '"permissions":{}', '"permissions":{"filesystem":[{"path":"/tmp/data","mode":"readwrite"}],"network":[{"host":"example.com","port":443}],"env":["API_KEY"]}');
good = strrep(good, '"limits":{}', '"limits":{"memoryMB":1,"cpuMillis":0,"timeoutMs":2,"maxInflight":3}');
good = strrep(good, '"health":{}', '"health":{"method":"ping","intervalMs":1}');
good = [good(1:end-1) ',"signature":{"algorithm":"ed25519","keyId":"key"},"sbom":"dist/sbom.json"}'];
assert(praxo.validate_manifest(good));
container = strrep(base, '"type":"process","command":"echo"', '"type":"container","image":"image"');
container = strrep(container, '"isolation":"process"', '"isolation":"container"');
assert(praxo.validate_manifest(container));
disp('test_manifest passed');
end

function value = field(node, name)
index = find(strcmp(node.value(:, 1), name), 1);
assert(~isempty(index));
value = node.value{index, 2};
end
