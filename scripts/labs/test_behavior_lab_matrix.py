import unittest

from scripts.labs import behavior_lab_matrix as matrix


class BehaviorLabMatrixTests(unittest.TestCase):
    def test_render_starts_with_generated_banner(self):
        report = {
            "run_id": "run-1",
            "repository": {"sha": "a" * 40, "dirty": False},
            "summary": {"cells": 1, "passed": 1, "unsupported": 0, "failed": 0},
            "scenarios": [
                {
                    "key": "initial-denial",
                    "languages": {
                        "go": {"status": "passed", "coverage": "scenario"},
                    },
                }
            ],
        }
        text = matrix.render(report, "en", "report.json")
        self.assertTrue(text.startswith(
            "<!-- Generated by scripts/labs/behavior_lab_matrix.py from a "
            "Behavior Lab JSON report; do not edit by hand. -->\n\n"
        ))
        self.assertIn("# Behavior Lab Matrix", text)


if __name__ == "__main__":
    unittest.main()
